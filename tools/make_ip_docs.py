def setup(doc, size):
    section = doc.sections[0]
    section.page_width, section.page_height = Twips(11906), Twips(16838)
    section.left_margin, section.right_margin = Cm(3), Cm(1.5)
    section.top_margin = section.bottom_margin = Cm(2)
    style = doc.styles["Normal"]
    style.font.name, style.font.size = "Times New Roman", Pt(size)
    style.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.paragraph_format.space_after, style.paragraph_format.space_before = Pt(0), Pt(0)
    style.paragraph_format.line_spacing = 1.0


def para(target, text="", bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, size=None, italic=False, highlight=False, space_after=0):
    p = target.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    if text:
        run = p.add_run(text)
        run.bold, run.italic = bold, italic
        if size:
            run.font.size = Pt(size)
        if highlight:
            run.font.highlight_color = WD_COLOR_INDEX.YELLOW
    return p


def lines(cell, items, first_bold=False):
    """Fill a table cell with paragraphs; '• ' items are bullets, '## ' items are bold sub-headings."""
    cell.paragraphs[0].text = ""
    for n, item in enumerate(items):
        p = cell.paragraphs[0] if n == 0 else cell.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        if isinstance(item, tuple) and item[0] == "img":
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            if (IMG / item[1]).exists():
                p.add_run().add_picture(str(IMG / item[1]), width=Cm(min(item[2], 12.4)))
            continue
        if isinstance(item, tuple) and item[0] == "caption":
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(item[1])
            run.italic = True
            p.paragraph_format.space_after = Pt(6)
            continue
        if isinstance(item, tuple) and item[0] == "mark":
            run = p.add_run(item[1])
            run.font.highlight_color = WD_COLOR_INDEX.YELLOW
            continue
        text = item
        bold = (first_bold and n == 0) or text.startswith("## ")
        run = p.add_run(text[3:] if text.startswith("## ") else text)
        run.bold = bold
        if bold and n:
            p.paragraph_format.space_before = Pt(6)


def borders(table):
    tbl = table._tbl
    props = tbl.tblPr
    edges = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), "000000")
        edges.append(el)
    props.append(edges)


