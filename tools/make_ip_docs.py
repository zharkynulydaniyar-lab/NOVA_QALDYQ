def abstract():
    doc = Document()
    setup(doc, 12)
    para(doc, "РЕФЕРАТ", bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=6)
    table = doc.add_table(rows=0, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    borders(table)
    for label, content in ROWS:
        row = table.add_row()
        row.cells[0].width, row.cells[1].width = Twips(2265), Twips(7375)
        row.cells[0].paragraphs[0].text = ""
        if label:
            run = row.cells[0].paragraphs[0].add_run(label)
            run.bold = True
        lines(row.cells[1], content)
    # Fixed layout with explicit grid widths, as in the sample (2265 + 7375 twips).
    table.autofit = False
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    table._tbl.tblPr.append(layout)
    width = OxmlElement("w:tblW")
    width.set(qn("w:w"), "9640")
    width.set(qn("w:type"), "dxa")
    for old in table._tbl.tblPr.findall(qn("w:tblW")):
        table._tbl.tblPr.remove(old)
    table._tbl.tblPr.append(width)
    for col, value in zip(table._tbl.tblGrid.findall(qn("w:gridCol")), ("2265", "7375")):
        col.set(qn("w:w"), value)
    for column, value in zip(table.columns, (Twips(2265), Twips(7375))):
        for cell in column.cells:
            cell.width = value
    path = OUT / "Qaldyq_Реферат.docx"
    doc.save(path)
    return path


def code_appendix():
    doc = Document()
    setup(doc, 10)
    para(doc, "ҚОСЫМША КОД", bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, size=12, space_after=6)
    para(doc, "Python", bold=True, align=WD_ALIGN_PARAGRAPH.LEFT)
    total = 0
    for name in CODE_FILES:
        path = ROOT / name
        if not path.exists():
            continue
        para(doc, "")
        para(doc, f"#{name}", bold=True, align=WD_ALIGN_PARAGRAPH.LEFT)
        para(doc, "")
        for line in path.read_text(encoding="utf-8").splitlines():
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.add_run(line.replace("\t", "    "))
            total += 1
    out = OUT / "Qaldyq_Қосымша_код.docx"
    doc.save(out)
    return out, total


