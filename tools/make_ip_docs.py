def ppr(paragraph, style=None, bullet=False, justify=True, first_line=False):
    p = paragraph._p
    pPr = p.get_or_add_pPr()
    if style:
        el = OxmlElement("w:pStyle")
        el.set(qn("w:val"), style)
        pPr.insert(0, el)
    if bullet:
        num = OxmlElement("w:numPr")
        lvl = OxmlElement("w:ilvl")
        lvl.set(qn("w:val"), "0")
        nid = OxmlElement("w:numId")
        nid.set(qn("w:val"), BULLET_NUM)
        num.append(lvl)
        num.append(nid)
        pPr.append(num)
    spacing = OxmlElement("w:spacing")
    spacing.set(qn("w:after"), "0")
    spacing.set(qn("w:line"), "240")
    spacing.set(qn("w:lineRule"), "auto")
    pPr.append(spacing)
    if first_line:
        ind = OxmlElement("w:ind")
        ind.set(qn("w:firstLine"), "567")
        pPr.append(ind)
    ctx = OxmlElement("w:contextualSpacing")
    pPr.append(ctx)
    if justify:
        jc = OxmlElement("w:jc")
        jc.set(qn("w:val"), "both")
        pPr.append(jc)


def runs(paragraph, text, size=12):
    """'**A **B' → bold A, regular B; '**text' → all bold."""
    parts = [("", text)]
    if text.startswith("**"):
        head, sep, tail = text[2:].partition(" **")
        parts = [("b", head + (" " if sep else ""))] + ([("", tail)] if sep else [])
    for kind, value in parts:
        if not value:
            continue
        run = paragraph.add_run(value)
        run.font.name, run.font.size = "Times New Roman", Pt(size)
        run._element.rPr.rFonts.set(qn("w:cs"), "Times New Roman")
        run.bold = kind == "b"


def fill(cell, items):
    cell.paragraphs[0]._p.getparent().remove(cell.paragraphs[0]._p)
    for item in items:
        p = cell.add_paragraph()
        if item.startswith("-"):
            ppr(p, "a6", bullet=True)
            runs(p, item[1:])
        elif item.startswith("#"):
            ppr(p, "a6")
            runs(p, "**" + item[1:])
        else:
            ppr(p, "a6" if item.startswith(("•", "**")) or not item else None)
            runs(p, item)
        if item.endswith("студенті, "):
            mark = p.add_run("(білім беру бағдарламасының шифры мен атауы)")
            mark.font.name, mark.font.size = "Times New Roman", Pt(12)
            mark.font.highlight_color = WD_COLOR_INDEX.YELLOW


def table_props(table):
    tblPr = table._tbl.tblPr
    for tag in ("w:tblStyle", "w:tblW", "w:tblInd", "w:tblLayout", "w:tblLook"):
        for old in tblPr.findall(qn(tag)):
            tblPr.remove(old)
    style = OxmlElement("w:tblStyle")
    style.set(qn("w:val"), "af9")
    width = OxmlElement("w:tblW")
    width.set(qn("w:w"), "9640")
    width.set(qn("w:type"), "dxa")
    indent = OxmlElement("w:tblInd")
    indent.set(qn("w:w"), "-147")
    indent.set(qn("w:type"), "dxa")
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    for el in (style, width, indent, layout):
        tblPr.append(el)
    for col, value in zip(table._tbl.tblGrid.findall(qn("w:gridCol")), ("2265", "7375")):
        col.set(qn("w:w"), value)
    for row in table.rows:
        for cell, value in zip(row.cells, ("2265", "7375")):
            tcPr = cell._tc.get_or_add_tcPr()
            for old in tcPr.findall(qn("w:tcW")):
                tcPr.remove(old)
            tcW = OxmlElement("w:tcW")
            tcW.set(qn("w:w"), value)
            tcW.set(qn("w:type"), "dxa")
            tcPr.append(tcW)


